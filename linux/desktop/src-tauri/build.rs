//! Build script.
//!
//! `tauri_build::build()` generates the application context and validates the
//! bundle configuration, including the `externalBin` sidecar. Tauri requires the
//! target-suffixed sidecar to exist before compiling, and a missing one fails
//! with an unhelpful `resource path ... doesn't exist`, so this script turns that
//! into actionable behaviour:
//!
//! * non-release builds (cargo check / cargo test / tauri dev) create a clearly
//!   marked placeholder when the real sidecar has not been packaged yet, so the
//!   Rust side stays buildable before the Python engine exists;
//! * release builds refuse to proceed when the sidecar is missing **or is still
//!   the placeholder**, because the packaged app would silently ship a fake
//!   engine. Run `linux/scripts/build-sidecar.sh` first.

use std::path::{Path, PathBuf};

const SIDECAR: &str = "translator-bridge";
/// Placeholder files contain this marker; release builds reject them.
const PLACEHOLDER_MARKER: &str = "translator-bridge placeholder";

fn main() {
    ensure_sidecar();
    tauri_build::build();
}

fn sidecar_path() -> PathBuf {
    let manifest =
        std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is always set for build scripts");
    let target = std::env::var("TARGET").expect("TARGET is always set for build scripts");
    Path::new(&manifest)
        .join("binaries")
        .join(format!("{SIDECAR}-{target}"))
}

fn placeholder_contents() -> String {
    format!(
        "#!/bin/sh\n# {PLACEHOLDER_MARKER}: generated by build.rs so that cargo check/test can run.\n\
         # Build the real engine with linux/scripts/build-sidecar.sh before packaging.\n\
         echo '{PLACEHOLDER_MARKER}: run linux/scripts/build-sidecar.sh' >&2\n\
         exit 1\n"
    )
}

fn ensure_sidecar() {
    let path = sidecar_path();
    let release = std::env::var("PROFILE").unwrap_or_default() == "release";
    if let Some(parent) = path.parent() {
        if !parent.exists() {
            std::fs::create_dir_all(parent)
                .unwrap_or_else(|error| panic!("failed to create {}: {error}", parent.display()));
        }
    }
    if path.exists() {
        if release
            && std::fs::read_to_string(&path).is_ok_and(|text| text.contains(PLACEHOLDER_MARKER))
        {
            panic!(
                "the packaged engine at {} is the debug placeholder.\n\
                 Run linux/scripts/build-sidecar.sh to build the real PyInstaller sidecar, then retry.",
                path.display()
            );
        }
        return;
    }
    if release {
        panic!(
            "missing sidecar binary {}.\n\
             Run linux/scripts/build-sidecar.sh first: it writes binaries/{SIDECAR}-<target-triple>.",
            path.display()
        );
    }
    std::fs::write(&path, placeholder_contents())
        .unwrap_or_else(|error| panic!("failed to write {}: {error}", path.display()));
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        if let Ok(metadata) = std::fs::metadata(&path) {
            let mut permissions = metadata.permissions();
            permissions.set_mode(0o755);
            let _ = std::fs::set_permissions(&path, permissions);
        }
    }
    println!(
        "cargo:warning=sidecar {} was missing for a non-release build; wrote a placeholder. \
         Run linux/scripts/build-sidecar.sh before packaging.",
        path.display()
    );
}
