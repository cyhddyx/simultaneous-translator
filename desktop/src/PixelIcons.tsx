import type { SVGProps } from "react";

type PixelIconProps = SVGProps<SVGSVGElement> & { size?: number | string };
type Block = [x: number, y: number, width: number, height: number];

// All artwork uses the same 16 × 16 grid and solid blocks, with no rounded strokes.
function icon(blocks: Block[]) {
  return function PixelIcon({ size = 16, ...props }: PixelIconProps) {
    return (
      <svg width={size} height={size} viewBox="0 0 16 16" fill="currentColor"
        shapeRendering="crispEdges" aria-hidden="true" focusable="false" {...props}>
        {blocks.map(([x, y, width, height], index) => (
          <rect key={index} x={x} y={y} width={width} height={height} />
        ))}
      </svg>
    );
  };
}

